def factors(n):
    f = {}
    p = 2
    while p*p <= n:
        while n % p == 0:
            f[p] = f.get(p, 0) + 1
            n //= p
        p += 1
    if n > 1:
        f[n] = f.get(n, 0) + 1
    return f

def sigma(n):
    return prod((p**(e+1)-1)//(p-1) for p,e in factors(n).items())

def first(a,b,start=0):
    for n,(x,y) in enumerate(zip(a,b),start):
        if x != y:
            return {'first_index':n,'a':x,'b':y,'agreement':n-start}
    return {'agreement':min(len(a),len(b)),'no_mismatch':True}

