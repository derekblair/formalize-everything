#!/usr/bin/env python3
"""Render the Lean numeric table from its cell-level provenance CSV (stdlib only)."""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VARIANTS = ['mt', 'sp', 'lxxSmith', 'lxxBrenton', 'lxxArp330', 'lxxShelah330']
NAMES = {
    'gen5': ['adam', 'seth', 'enosh', 'kenan', 'mahalalel', 'jared', 'enoch',
             'methuselah', 'lamech', 'noah'],
    'gen11': ['shem', 'arpachshad', 'kainan', 'shelah', 'eber', 'peleg', 'reu',
              'serug', 'nahor', 'terah'],
}
FIELDS = ['begetting', 'remaining', 'lifespan']

def render():
    with (ROOT / 'data/provenance.csv').open(newline='') as file:
        cells = list(csv.DictReader(file))
    indexed = {}
    for cell in cells:
        key = tuple(cell[k] for k in ['variant', 'chapter', 'patriarch', 'field'])
        assert key not in indexed, f'Duplicate cell: {key}'
        assert cell['source'] and cell['locator'], f'Missing provenance: {key}'
        if cell['value']:
            assert cell['status'] == 'SOURCED', f'Unverified value: {key}'
            assert cell['value'].isdigit(), f'Non-natural value: {key}'
        else:
            assert cell['status'] in ['NOT_STATED', 'ABSENT_PATRIARCH'], key
        indexed[key] = cell
    expected = {(v, ch, p, field) for v in VARIANTS for ch, ps in NAMES.items()
                for p in ps for field in FIELDS}
    assert set(indexed) == expected, 'Cell inventory differs from declared domains'
    result = '''import Std

/-!
# Sourced genealogy data

Generated by `scripts/generate_data.py` from `data/provenance.csv` and
`data/chronology-inputs.csv`. Run that script with `--check` to check agreement.
See PROVENANCE.md for source editions, absent versus unstated fields, source
reconstructions, and precisely what each LXX dataset profile represents.
No numeral here is an inferred lifespan disguised as an explicit textual cell.
-/

namespace BibleNumbers

inductive Chapter where
  | gen5 | gen11
  deriving DecidableEq, BEq, Repr

inductive Patriarch where
  | adam | seth | enosh | kenan | mahalalel | jared | enoch | methuselah | lamech | noah
  | shem | arpachshad | kainan | shelah | eber | peleg | reu | serug | nahor | terah
  deriving DecidableEq, BEq, Repr

inductive Field where
  | begetting | remaining | lifespan
  deriving DecidableEq, BEq, Repr

/-- These are named source profiles, not an assertion that all LXX manuscripts
agree. `lxxArp330` isolates the second Arpachshad reading printed by Smith;
`lxxShelah330` applies Brenton's printed Alexandrinus numerical apparatus. -/
inductive Variant where
  | mt | sp | lxxSmith | lxxBrenton | lxxArp330 | lxxShelah330
  deriving DecidableEq, BEq, Repr

inductive Witness where
  | mt | lxx | sp
  deriving DecidableEq, BEq, Repr

def witnessOf : Variant → Witness
  | .mt => .mt
  | .sp => .sp
  | _ => .lxx

/-- Remaining years means after the reported begetting event. In particular,
Noah's 350 post-Flood years are not a remaining-after-begetting entry. `none`
is an explicitly documented absence of a stated number, never an unknown zero. -/
structure Row where
  begetting : Nat
  remaining : Option Nat
  lifespan : Option Nat
  deriving DecidableEq, BEq, Repr

def chapters : List Chapter := [.gen5, .gen11]

def fields : List Field := [.begetting, .remaining, .lifespan]

def variants : List Variant :=
  [.mt, .sp, .lxxSmith, .lxxBrenton, .lxxArp330, .lxxShelah330]

'''
    all_names = NAMES['gen5'] + NAMES['gen11']
    result += 'def allPatriarchs : List Patriarch :=\n  [' + ', '.join('.' + p for p in all_names) + ']\n\n'
    result += 'def patriarchs : Chapter → List Patriarch\n'
    for ch, names in NAMES.items():
        result += '  | .' + ch + ' => [' + ', '.join('.' + p for p in names) + ']\n'
    result += '''
/-- `none` at row level means the patriarch is absent from this chapter/profile.
At field level it means the source does not explicitly state that field. -/
def row : Variant → Chapter → Patriarch → Option Row
'''
    for variant in VARIANTS:
        for chapter, names in NAMES.items():
            for patriarch in names:
                entries = [indexed[(variant, chapter, patriarch, field)] for field in FIELDS]
                if entries[0]['status'] == 'ABSENT_PATRIARCH':
                    assert all(c['status'] == 'ABSENT_PATRIARCH' for c in entries)
                    continue
                assert entries[0]['value'], 'Every present row must have sourced begetting age'
                values = [entries[0]['value']] + [
                    'some ' + c['value'] if c['value'] else 'none' for c in entries[1:]]
                result += f'  | .{variant}, .{chapter}, .{patriarch} => some ⟨' + ', '.join(values) + '⟩\n'
    result += '''  | _, _, _ => none

def cell (v : Variant) (c : Chapter) (p : Patriarch) (f : Field) : Option Nat :=
  (row v c p).bind fun r =>
    match f with
    | .begetting => some r.begetting
    | .remaining => r.remaining
    | .lifespan => r.lifespan

'''
    with (ROOT / 'data/chronology-inputs.csv').open(newline='') as file:
        inputs = list(csv.DictReader(file))
    assert len(inputs) == 2 * len(VARIANTS)
    for lean_name, field, doc in [
        ('noahFloodAge', 'floodAge', 'Genesis 7:6, cross-checked by Millam Table 7 Noah row.'),
        ('floodToArpachshad', 'yearsAfterFlood', 'Genesis 11:10; Smith Tables 1/3/4 coordinates also give this offset.'),
    ]:
        result += f'/-- {doc} -/\ndef {lean_name} : Variant → Nat\n'
        for variant in VARIANTS:
            matches = [c for c in inputs if c['variant'] == variant and c['field'] == field]
            assert len(matches) == 1
            c = matches[0]
            assert c['status'] == 'SOURCED' and c['value'].isdigit()
            assert c['source'] and c['locator']
            result += f"  | .{variant} => {c['value']}\n"
        result += '\n'
    result += 'end BibleNumbers\n'
    return result

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'BibleNumbers/Data.lean'
    rendered = render()
    if args.check:
        assert output.read_text() == rendered, 'Data.lean is out of sync with provenance CSV'
        print('Provenance check passed: 360 genealogy cells and 12 chronology inputs.')
    else:
        output.write_text(rendered)
        print(f'Generated {output}')
